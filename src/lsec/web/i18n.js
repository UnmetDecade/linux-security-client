/* Server messages that embed counts or a subordinate message. */
const SERVER_TEXT_PATTERNS = [
  [/^(\d+) unhandled critical events$/, (m) => `${m[1]} 条未处理的严重事件`],
  [/^(\d+) unhandled high-severity events$/, (m) => `${m[1]} 条未处理的高危事件`],
  [/^(\d+) containers with configuration risks detected$/, (m) => `${m[1]} 个容器存在配置风险`],
  [/^(\d+) rule packs active; a rule match is not equivalent to confirmed malware$/, (m) => `${m[1]} 个规则包已激活；规则命中不等于已确认恶意软件`],
  [/^container monitoring unavailable: (.*)$/, (m) => `容器监控不可用：${m[1]}`],
  [/^probe failed: (.*)$/, (m) => `探测失败：${m[1]}`],
  [/^read-only Docker API error: (.*)$/, (m) => `只读 Docker API 错误：${m[1]}`],
];

const LANG_STORAGE_KEY = 'lsec_lang';
let LANG = 'en';

try {
  const stored = localStorage.getItem(LANG_STORAGE_KEY);
  if (stored === 'en' || stored === 'zh') LANG = stored;
} catch (err) { /* storage may be unavailable; keep the default */ }

document.documentElement.lang = LANG === 'zh' ? 'zh-CN' : 'en';

function t(key, vars) {
  const table = MESSAGES[LANG] || MESSAGES.en;
  let value = table[key];
  if (value === undefined) value = MESSAGES.en[key];
  if (value === undefined) value = key;
  if (vars) {
    value = value.replace(/\{(\w+)\}/g, (match, name) => (
      Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
    ));
  }
  return value;
}

function tServerLabel(value) {
  if (LANG !== 'zh' || value === null || value === undefined) return value;
  return SERVER_LABELS.zh[value] || value;
}

/* Translate a server-emitted presentation string when a mapping exists.
   Unknown text is returned unchanged. */
function tServerText(value) {
  if (LANG !== 'zh' || typeof value !== 'string' || value === '') return value;
  const exact = SERVER_TEXT.zh[value];
  if (exact !== undefined) return exact;
  for (const [pattern, render] of SERVER_TEXT_PATTERNS) {
    const match = pattern.exec(value);
    if (match) return render(match);
  }
  return value;
}

/* Same as tServerText, but for values that may be a list of strings. */
function tServerTextList(values) {
  if (!Array.isArray(values)) return values;
  return values.map((value) => tServerText(value));
}

function setLang(lang) {
  LANG = lang === 'zh' ? 'zh' : 'en';
  try { localStorage.setItem(LANG_STORAGE_KEY, LANG); } catch (err) { /* ignore */ }
  document.documentElement.lang = LANG === 'zh' ? 'zh-CN' : 'en';
  applyStaticTranslations();
  /* Reload so every rendered page and the page metadata use the new language. */
  location.reload();
}

function applyStaticTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-attr]').forEach((node) => {
    node.dataset.i18nAttr.split(';').forEach((entry) => {
      const separator = entry.indexOf(':');
      if (separator < 0) return;
      const attr = entry.slice(0, separator).trim();
      const key = entry.slice(separator + 1).trim();
      if (attr && key) node.setAttribute(attr, t(key));
    });
  });
}

function initLanguageSwitch() {
  document.querySelectorAll('[data-lang]').forEach((button) => {
    const active = button.dataset.lang === LANG;
    button.classList.toggle('active', active);
    button.setAttribute('aria-pressed', String(active));
    button.addEventListener('click', () => {
      if (button.dataset.lang !== LANG) setLang(button.dataset.lang);
    });
  });
}

function initI18n() {
  applyStaticTranslations();
  initLanguageSwitch();
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initI18n);
} else {
  initI18n();
}
